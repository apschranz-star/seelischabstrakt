/*
 * Builds app/js/data/scelte.js: the vegetables and fruit Sofia can pick in the
 * meal builder, and stand-ins for plan foods that have no composition data,
 * with their values per 100 g copied from the bundled CIQUAL 2020 table.
 * Small on purpose, so the builder and the daily totals work without loading
 * the whole table.  Run: node tools/genera-scelte.mjs
 */
import { writeFileSync } from "node:fs";
import { CIBI, CAMPI, FONTE } from "../app/js/data/ciqual.js";

const I = Object.fromEntries(CAMPI.map((k, i) => [k, i]));
const per = Object.fromEntries(CIBI.map((c) => [c[0], c]));
const TENUTI = ["kcal", "prot", "carb", "fat", "sug", "fib", "salt", "k", "p", "ca", "fe", "vitc", "fol", "epa", "dha"];

function valori(codice) {
  const c = per[codice];
  if (!c) throw new Error("CIQUAL code not found: " + codice);
  if (c[I.kcal] == null) throw new Error("no energy for " + codice);
  const v = {};
  for (const k of TENUTI) if (c[I[k]] != null) v[k] = c[I[k]];
  return { codice, nomeEn: c[I.nome], stimaKcal: c[I.stimaKcal], v };
}

