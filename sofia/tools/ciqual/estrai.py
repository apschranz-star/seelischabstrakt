"""Extract the CIQUAL 2020 food composition table (ANSES, English edition) into
app/js/data/ciqual.js for the Sofia app.

Source: "CIQUAL food composition table 2020", Zenodo record 4770202
(https://zenodo.org/records/4770202, file "Table Ciqual 2020_ENG_2020 07 07.xls",
sha256 5551841f12f40fb6c869f80aa14e9db33bcfb7dcc135f000cb994a2cca4dc2f5), a copy of
the official table (ciqual.anses.fr). Needs xlrd (pip install xlrd).

Usage: python3 -I tools/ciqual/estrai.py <table.xls> app/js/data/ciqual.js

Values: '-' -> null, 'traces' -> 0, '< x' -> 0 (below the quantification
limit), comma decimals. Energy: the EU 1169/2011 value; when the table has none,
the Jones-factor value (stimaKcal 1); when neither, 4/4/9/2 kcal per g of
protein, carbohydrate, fat and fibre (stimaKcal 2). Baby foods are left out."""
import sys, json, re, xlrd
wb = xlrd.open_workbook(sys.argv[1])
sh = wb.sheet_by_index(0)
hdr = [str(c.value) for c in sh.row(0)]
col = {h: i for i, h in enumerate(hdr)}
CAMPI = [
  ("kcal", "Energy, Regulation EU No 1169/2011 (kcal/100g)"),
  ("kcalJ", "Energy, N x Jones' factor, with fibres (kcal/100g)"),
  ("prot", "Protein (g/100g)"),
  ("carb", "Carbohydrate (g/100g)"),
  ("fat", "Fat (g/100g)"),
  ("sug", "Sugars (g/100g)"),
  ("fib", "Fibres (g/100g)"),
  ("sat", "FA saturated (g/100g)"),
  ("salt", "Salt (g/100g)"),
  ("na", "Sodium (mg/100g)"),
  ("k", "Potassium (mg/100g)"),
  ("p", "Phosphorus (mg/100g)"),
  ("ca", "Calcium (mg/100g)"),
  ("fe", "Iron (mg/100g)"),
  ("mg", "Magnesium (mg/100g)"),
  ("vitc", "Vitamin C (mg/100g)"),
  ("vitd", "Vitamin D (µg/100g)"),
  ("b12", "Vitamin B12 (µg/100g)"),
  ("fol", "Vitamin B9 or Folate (µg/100g)"),
  ("epa", "FA 20:5 5c,8c,11c,14c,17c (n-3) EPA (g/100g)"),
  ("dha", "FA 22:6 4c,7c,10c,13c,16c,19c (n-3) DHA (g/100g)"),
  ("ala", "FA 18:3 c9,c12,c15 (n-3) (g/100g)"),
]
def val(x):
    s = str(x).strip().replace(",", ".")
    if s in ("", "-"): return None
    if s.lower().startswith("trace"): return 0
    if s.startswith("<"): return 0
    try: return round(float(s), 3)
    except ValueError: return None
cibi, gruppi = [], {}
for r in range(1, sh.nrows):
    row = sh.row(r)
    g = lambda h: row[col[h]].value
    code = g("alim_code")
    try: code = int(float(code))
    except Exception: continue
    grp, ssg = str(g("alim_grp_code")).strip(), str(g("alim_ssgrp_code")).strip()
    gruppi.setdefault(grp, str(g("alim_grp_nom_eng")).strip())
    gruppi.setdefault(ssg, str(g("alim_ssgrp_nom_eng")).strip())
    nome = re.sub(r"\s+", " ", str(g("alim_nom_eng")).strip()).replace(" -> ARCHIVE", "")
    if grp == "11": continue  # baby food
    v = [val(g(h)) for _, h in CAMPI]
    d = dict(zip([k for k, _ in CAMPI], v))
    stima = 0
    if d["kcal"] is None:
        if d["kcalJ"] is not None: d["kcal"], stima = d["kcalJ"], 1
        elif None not in (d["prot"], d["carb"], d["fat"]):
            d["kcal"], stima = round(4 * d["prot"] + 4 * d["carb"] + 9 * d["fat"] + 2 * (d["fib"] or 0), 1), 2
    del d["kcalJ"]
    cibi.append([code, nome, ssg, stima] + list(d.values()))
campi = ["code", "nome", "gruppo", "stimaKcal"] + [k for k, _ in CAMPI if k != "kcalJ"]
num = lambda x: "null" if x is None else (str(int(x)) if float(x).is_integer() else repr(round(x, 3)))
righe = ",\n".join("[" + ",".join([str(c[0]), json.dumps(c[1], ensure_ascii=False), json.dumps(c[2]), str(c[3])] + [num(x) for x in c[4:]]) + "]" for c in cibi)
with open(sys.argv[2], "w") as f:
    f.write("/* Generated by tools/ciqual/estrai.py from ANSES CIQUAL 2020 (English table). Do not edit.\n")
    f.write("   Licence: Etalab Open Licence 2.0 (the Zenodo copy: CC BY 4.0). Credit: ANSES, Ciqual French food composition table 2020. */\n")
    f.write("export const FONTE = " + json.dumps({"nome": "ANSES CIQUAL 2020", "url": "https://ciqual.anses.fr/", "copia": "https://zenodo.org/records/4770202", "sha256": "5551841f12f40fb6c869f80aa14e9db33bcfb7dcc135f000cb994a2cca4dc2f5"}) + ";\n")
    f.write("export const CAMPI = " + json.dumps(campi) + ";\n")
    f.write("export const GRUPPI = " + json.dumps(gruppi, ensure_ascii=False) + ";\n")
    f.write("export const CIBI = [\n" + righe + "\n];\n")
print(len(cibi), "foods,", len(gruppi), "groups")
